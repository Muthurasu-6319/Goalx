export const REGISTERED_COLLECTION_NAMES = new Set(COLLECTION_REGISTRY.map((c) => c.name));

export function getCollectionsForExport(
  group: 'personal' | 'business' | 'competitor' | 'all',
  includeSalary = false
): CollectionRegistryEntry[] {
  return COLLECTION_REGISTRY.filter((entry) => {
    if (entry.exportGroup === 'none') return false;
    if (entry.sensitiveSalary && !includeSalary) return false;
    if (group === 'all') return true;
    return entry.exportGroup === group;
  });
}

export function getCollectionsForModuleDelete(
  moduleGroup: DeleteModuleGroup
): CollectionRegistryEntry[] {
  return COLLECTION_REGISTRY.filter(
    (entry) => entry.deleteModuleGroup === moduleGroup && !entry.immutableInRules
  );
}
